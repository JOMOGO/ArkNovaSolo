#!/usr/bin/env python3
"""Bundle arno/**/*.lua into one Lua block with a tiny module registry.

MoonSharp in TTS has no runtime `require`, so each module file becomes a loader
function in ARNO_MODULES; `arno_require(name)` loads lazily and caches. Inside a
module the loader's parameter is called `require`, so module code reads naturally:
    local rng = require("core.rng")
Module names are paths relative to arno/ without ".lua", with "/" -> ".".
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARNO_DIR = ROOT / "arno"

BEGIN = "-- BEGIN ARNO BUNDLE (generated by tools/lua_bundle.py; do not edit)"
END = "-- END ARNO BUNDLE"

PRELUDE = """\
local ARNO_MODULES, ARNO_LOADED = {}, {}
local function arno_require(name)
  local loaded = ARNO_LOADED[name]
  if loaded ~= nil then return loaded end
  local loader = ARNO_MODULES[name]
  if loader == nil then error("ARNO module not found: " .. tostring(name)) end
  loaded = loader(arno_require)
  if loaded == nil then loaded = true end
  ARNO_LOADED[name] = loaded
  return loaded
end
"""


def module_name(path: Path, base: Path = ARNO_DIR) -> str:
    return path.relative_to(base).with_suffix("").as_posix().replace("/", ".")


def module_files(base: Path = ARNO_DIR, packages: tuple[str, ...] | None = None) -> list[Path]:
    files = sorted(base.rglob("*.lua"))
    if packages is not None:
        files = [f for f in files if module_name(f, base).split(".")[0] in packages]
    return files


STRICT_PRELUDE = """\
-- tests only: an ARNO module may set a global the mod has (ARNO_MOD_GLOBALS, or one with a
-- value) or one of ARNO's own (CHANGES.md §3: ARNO, arno_state, arno_setup, on_arno_*,
-- arno_back_clicked); any other new global is a mistake, usually a missing `local`
local ARNO_MOD_GLOBALS = {%s}
local function arno_strict_env(module)
  return setmetatable({}, {
    __index = _G,
    __newindex = function(_, k, v)
      if rawget(_G, k) ~= nil or ARNO_MOD_GLOBALS[k] or k == "ARNO" or k == "arno_state"
         or k == "arno_setup" or k == "arno_back_clicked"
         or (type(k) == "string" and k:match("^on_arno_")) then
        rawset(_G, k, v)
      else
        error("ARNO module " .. module .. " sets a new global: " .. tostring(k), 2)
      end
    end,
  })
end
"""


def bundle(base: Path = ARNO_DIR, packages: tuple[str, ...] | None = None, epilogue: str = "",
           strict_globals: list[str] | None = None) -> str:
    """Return the bundle text (LF line endings). `epilogue` is appended inside the block.

    With `strict_globals` (tests only), each module runs in an environment that refuses new
    globals other than those names and ARNO's own (STRICT_PRELUDE).
    """
    parts = [BEGIN, "\n", PRELUDE]
    prologue = ""
    if strict_globals is not None:
        parts.append(STRICT_PRELUDE % ", ".join(f"{name} = true" for name in sorted(set(strict_globals))))
    for f in module_files(base, packages):
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n")
        if not text.endswith("\n"):
            text += "\n"
        name = module_name(f, base)
        if strict_globals is not None:
            prologue = f'local _ENV = arno_strict_env("{name}")\n'
        parts.append(f'ARNO_MODULES["{name}"] = function(require)\n{prologue}{text}end\n')
    parts.append(epilogue)
    parts.append(END + "\n")
    return "".join(parts)
