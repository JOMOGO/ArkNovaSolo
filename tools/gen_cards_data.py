#!/usr/bin/env python3
"""Generate arno/core/cards_data.lua from the helper's Cards.ts (via the harness JSON).

The ARNO action tables are copied mechanically, never retyped. Run after the harness
(build/harness/ts_reference.json). With --check, fail if the committed file is stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "build" / "harness" / "ts_reference.json"
OUT = ROOT / "arno" / "core" / "cards_data.lua"

FIELDS = (("action", "action"), ("amount", "amount"), ("slotAmount", "slot_amount"),
          ("slotFilter", "slot_filter"), ("difficultyLevelFilter", "level_filter"),
          ("fallback", "fallback"))

HEADER = """\
-- ARNO 3.0 for "Ark Nova - Complete Scripted" (Tabletop Simulator).
-- Port of brdgm/ark-nova-solo-helper (c) Stefan Seifert, Apache License 2.0.
-- ARNO solo mode designed by Andre K. See NOTICE. Modified: ported to Lua (MoonSharp).
--
-- GENERATED by tools/gen_cards_data.py from src/services/Cards.ts. Do not edit.
-- Order and content are identical to Cards.getAll().

return {
"""


def lua_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(v)


def render(cards) -> str:
    out = [HEADER]
    for card in cards:
        out.append(f'  {{ name = {json.dumps(card["name"])},\n')
        for side, key in (("standard", "standardActions"), ("upgraded", "upgradedActions")):
            out.append(f"    {side} = {{\n")
            for action in card[key]:
                parts = [f"{lua}={lua_value(action[ts])}" for ts, lua in FIELDS if ts in action]
                out.append("      { " + ", ".join(parts) + " },\n")
            out.append("    },\n")
        out.append("  },\n")
    out.append("}\n")
    return "".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    known = {ts for ts, _ in FIELDS} | {"name", "standardActions", "upgradedActions"}
    cards = json.loads(REF.read_text(encoding="utf-8"))["cards"]
    for card in cards:
        for key in ("standardActions", "upgradedActions"):
            for action in card[key]:
                unknown = set(action) - known
                if unknown:
                    raise SystemExit(f"Cards.ts has fields this generator does not know: {unknown}")
    text = render(cards)
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run tools/gen_cards_data.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
